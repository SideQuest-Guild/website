"""Battle.net recipe id translation: ``SkillLineAbility`` row id to the game's recipe (spell) id.

Battle.net's character professions endpoint (``characters.professions(slug)``) answers known recipes by
``SkillLineAbility`` id, a different id space from the game's recipe id (the addon contract's ``recipes[].id``,
and ``ProfessionRecipe.recipe_id``). ``battlenet_recipe_map.json`` is the exact translation table for one game
build, generated by ``tools/generate_battlenet_recipe_map.py`` from wago.tools' client data. Regenerate it after a
build that changes recipe ids (a new expansion patch); until then the same file works for every Forever build.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import NamedTuple

_MAP_PATH = Path(__file__).parent / "battlenet_recipe_map.json"


class TranslatedRecipe(NamedTuple):
    """One recipe in the game's own id space, after translating Battle.net's ``SkillLineAbility`` id."""

    recipe_id: int
    item_id: int | None


def _load() -> dict[int, TranslatedRecipe]:
    document = json.loads(_MAP_PATH.read_text())
    return {
        int(battlenet_id): TranslatedRecipe(recipe_id=entry["spell"], item_id=entry["item"])
        for battlenet_id, entry in document["recipes"].items()
    }


_recipes = _load()


def translate_recipe(battlenet_recipe_id: int) -> TranslatedRecipe | None:
    """The game recipe id (and created item id, if known) for a Battle.net ``known_recipes[].id``.

    ``None`` if the mapping has no entry: a recipe from a profession or build the map doesn't cover. Callers must
    skip these, never inventing an id.
    """
    return _recipes.get(battlenet_recipe_id)
